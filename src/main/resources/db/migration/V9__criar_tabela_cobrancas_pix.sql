-- Cobrança Pix gerada pelo Mercado Pago para um pagamento PENDENTE.
-- O pagamento vira CONFIRMADO quando o pedido (order) é pago no Mercado Pago.
CREATE TABLE comandavision.cobrancas_pix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pagamento_id BIGINT NOT NULL,
    pedido_mercado_pago VARCHAR(64) NOT NULL,
    qr_code TEXT NOT NULL,
    qr_code_base64 TEXT NOT NULL,
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_cobrancas_pix PRIMARY KEY (id),

    CONSTRAINT fk_cobrancas_pix_pagamento
        FOREIGN KEY (pagamento_id)
        REFERENCES comandavision.pagamentos (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_cobrancas_pix_pagamento UNIQUE (pagamento_id),
    CONSTRAINT uk_cobrancas_pix_pedido UNIQUE (pedido_mercado_pago)
);
